class NetworksCourse:
    """فئة رئيسية لإدارة منصة تعليم شبكات الحاسب"""
    
    def __init__(self):
        self.current_user = None
        self.quiz_results = []
        self.start_time = None
        
    def display_header(self):
        """عرض رأس البرنامج"""
        print("\n" + "="*70)
        print("🌐 منصة تعليم شبكات الحاسب 🌐".center(70))
        print("="*70)
        
    def display_menu(self):
        """عرض القائمة الرئيسية"""
        print("\n" + "─"*70)
        print("[1] 📚 عرض الدروس التعليمية")
        print("[2] ❓ بدء الاختبار")
        print("[3] 📊 عرض إحصائيات الأسئلة")
        print("[4] 🔍 البحث عن درس معين")
        print("[5] 📈 عرض نتائجك السابقة")
        print("[6] 🚪 خروج")
        print("─"*70)
        
    def display_lessons_menu(self):
        """عرض قائمة الدروس"""
        print("\n" + "="*70)
        print("📚 الدروس المتاحة".center(70))
        print("="*70)
        
        for lesson_id, lesson_data in LESSONS.items():
            print(f"\n[{lesson_id}] {lesson_data['title']}")
        
        print(f"\n[0] العودة للقائمة الرئيسية")
        
    def display_lesson(self, lesson_id: int):
        """عرض محتوى درس معين"""
        if lesson_id in LESSONS:
            lesson = LESSONS[lesson_id]
            print("\n" + lesson['content'])
            input("\n👈 اضغط Enter للعودة...")
        else:
            print("❌ الدرس غير موجود!")
            
    def start_quiz(self):
        """بدء الاختبار"""
        self.start_time = time.time()
        self.quiz_results = []
        
        print("\n" + "="*70)
        print("❓ اختبار شبكات الحاسب".center(70))
        print("="*70)
        print(f"\nسيتم طرح عليك {len(QUIZ_QUESTIONS)} أسئلة")
        print("اختر الإجابة الصحيحة من بين الخيارات")
        print("─"*70)
        
        input("\n👈 اضغط Enter للبدء...")
        
        for idx, question_data in enumerate(QUIZ_QUESTIONS, 1):
            self._ask_question(idx, question_data)
            
        self._show_results()
        
    def _ask_question(self, question_num: int, question_data: Dict):
        """طرح سؤال واحد"""
        print(f"\n{'─'*70}")
        print(f"السؤال {question_num}/{len(QUIZ_QUESTIONS)}")
        print(f"{'─'*70}")
        print(f"\n📝 {question_data['question']}\n")
        
        for option, text in question_data['options'].items():
            print(f"   ({option}) {text}")
        
        # أخذ الإجابة من المستخدم
        while True:
            user_answer = input("\n👉 إجابتك (A/B/C/D): ").strip().upper()
            if user_answer in ['A', 'B', 'C', 'D']:
                break
            print("❌ الرجاء إدخال خيار صحيح (A أو B أو C أو D)")
        
        # التحقق من الإجابة
        is_correct = user_answer == question_data['correct']
        
        # عرض النتيجة الفورية
        if is_correct:
            print("\n✅ إجابة صحيحة!")
        else:
            print(f"\n❌ إجابة خاطئة!")
            print(f"   الإجابة الصحيحة: ({question_data['correct']}) {question_data['options'][question_data['correct']]}")
        
        # عرض الشرح
        print(f"\n📝 الشرح: {question_data['explanation']}")
        
        # حفظ النتيجة
        self.quiz_results.append({
            'question_num': question_num,
            'is_correct': is_correct,
            'user_answer': user_answer,
            'correct_answer': question_data['correct']
        })
        
        input("\n👈 اضغط Enter للسؤال التالي...")
        
    def _show_results(self):
        """عرض نتائج الاختبار النهائية"""
        elapsed_time = time.time() - self.start_time
        minutes = int(elapsed_time // 60)
        seconds = int(elapsed_time % 60)
        
        correct_count = sum(1 for r in self.quiz_results if r['is_correct'])
        total_count = len(self.quiz_results)
        percentage = (correct_count / total_count * 100) if total_count > 0 else 0
        
        print("\n" + "="*70)
        print("📊 النتائج النهائية".center(70))
        print("="*70)
        
        print(f"\n🎯 الدرجة: {percentage:.1f}%")
        print(f"✅ الإجابات الصحيحة: {correct_count}/{total_count}")
        print(f"❌ الإجابات الخاطئة: {total_count - correct_count}/{total_count}")
        print(f"⏱️  الوقت المستغرق: {minutes} دقيقة و {seconds} ثانية")
        
        # التقييم
        if percentage >= 90:
            rating = "⭐⭐⭐⭐⭐ ممتاز جداً! فهمك للموضوع قوي جداً!"
        elif percentage >= 75:
            rating = "⭐⭐⭐⭐ جيد جداً! استمر في الاجتهاد!"
        elif percentage >= 60:
            rating = "⭐⭐⭐ جيد! لكن يمكن تحسن أفضل"
        elif percentage >= 50:
            rating = "⭐⭐ مقبول. ركز على الأساسيات أكثر"
        else:
            rating = "⭐ ضعيف. يُنصح بإعادة الدروس مجدداً"
        
        print(f"\n{rating}\n")
        
        input("👈 اضغط Enter للعودة للقائمة الرئيسية...")
        
    def show_statistics(self):
        """عرض إحصائيات الأسئلة"""
        print("\n" + "="*70)
        print("📊 إحصائيات الأسئلة".center(70))
        print("="*70)
        
        print(f"\n📝 إجمالي الأسئلة: {len(QUIZ_QUESTIONS)}")
        print(f"📚 عدد الدروس: {len(LESSONS)}")
        
        print("\n📋 توزيع الأسئلة:")
        print(f"   • أسئلة عامة: 10 أسئلة")
        print(f"   • المستوى: متوسط إلى متقدم")
        
        print("\n📊 موضوعات الأسئلة:")
        print(f"   • تعريف الشبكات: 1 سؤال")
        print(f"   • أنواع الشبكات: 1 سؤال")
        print(f"   • نموذج OSI: 2 سؤال")
        print(f"   • البروتوكولات: 2 سؤال")
        print(f"   • عنوان IP: 2 سؤال")
        print(f"   • الأجهزة والمعدات: 2 سؤال")
        
        input("\n👈 اضغط Enter للعودة...")
        
    def search_lesson(self):
        """البحث عن درس معين"""
        print("\n" + "="*70)
        print("🔍 البحث عن درس".center(70))
        print("="*70)
        
        keyword = input("\n🔎 أدخل كلمة البحث: ").strip().lower()
        
        results = []
        for lesson_id, lesson_data in LESSONS.items():
            if keyword in lesson_data['title'].lower() or keyword in lesson_data['content'].lower():
                results.append((lesson_id, lesson_data['title']))
        
        if results:
            print(f"\n✅ تم العثور على {len(results)} نتيجة:")
            for lesson_id, title in results:
                print(f"   [{lesson_id}] {title}")
        else:
            print(f"\n❌ لم يتم العثور على نتائج لـ '{keyword}'")
        
        input("\n👈 اضغط Enter للعودة...")
        
    def show_previous_results(self):
        """عرض النتائج السابقة"""
        if not self.quiz_results:
            print("\n❌ لا توجد نتائج سابقة. قم بإجراء الاختبار أولاً!")
            input("👈 اضغط Enter...")
            return
        
        print("\n" + "="*70)
        print("📈 النتائج السابقة".center(70))
        print("="*70)
        
        correct_count = sum(1 for r in self.quiz_results if r['is_correct'])
        total_count = len(self.quiz_results)
        percentage = (correct_count / total_count * 100)
        
        print(f"\n📊 ملخص النتيجة:")
        print(f"   • النسبة المئوية: {percentage:.1f}%")
        print(f"   • الإجابات الصحيحة: {correct_count}/{total_count}")
        print(f"   • معدل النجاح: {'✅ نجح' if percentage >= 50 else '❌ لم ينجح'}")
        
        input("\n👈 اضغط Enter للعودة...")
        
    def run(self):
        """تشغيل البرنامج الرئيسي"""
        while True:
            self.display_header()
            self.display_menu()
            
            choice = input("\n👉 اختر من القائمة (1-6): ").strip()
            
            if choice == '1':
                self._show_lessons_section()
            elif choice == '2':
                self.start_quiz()
            elif choice == '3':
                self.show_statistics()
            elif choice == '4':
                self.search_lesson()
            elif choice == '5':
                self.show_previous_results()
            elif choice == '6':
                print("\n👋 شكراً لاستخدامك المنصة! وداعاً!")
                break
            else:
                print("❌ اختيار غير صحيح! الرجاء المحاولة مجدداً")
    
    def _show_lessons_section(self):
        """قسم الدروس"""
        while True:
            self.display_lessons_menu()
            
            choice = input("\n👉 اختر رقم الدرس (0-6): ").strip()
            
            if choice == '0':
                break
            elif choice in [str(i) for i in range(1, 7)]:
                self.display_lesson(int(choice))
            else:
                print("❌ اختيار غير صحيح!")

